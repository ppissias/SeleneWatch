# Writes packaging/licenses/Qt-third-party-notices.txt: the notices and
# license texts of the third-party code inside the Qt DLLs and plugins a
# SeleneWatch release ships (Qt Core, Qt Gui, Qt Network with its Windows
# plugins; Qt Widgets has none of its own). They come from the attribution pages of the
# Qt documentation installed with Qt. Run it again when Qt is upgraded:
#
#   powershell -File packaging\make_qt_notices.ps1 -QtDocs C:\dev\tools\Qt\Docs\Qt-6.12.0 -QtVersion 6.12.0
#
# Pages for other platforms (Android, macOS, Linux/X11) are left out.
param(
    [Parameter(Mandatory)][string]$QtDocs,
    [Parameter(Mandatory)][string]$QtVersion
)
$ErrorActionPreference = 'Stop'
$skip = 'android|cocoa|xcb|forkfd|kwin|extra-cmake-modules|qeventdispatcher-cf|xserverhelper'
$pages = foreach ($module in 'qtcore', 'qtgui', 'qtnetwork') {
    Get-ChildItem (Join-Path $QtDocs $module) -Filter "$module-attribution-*.html" | Where-Object { $_.Name -notmatch $skip }
}
if (-not $pages) { throw "No attribution pages under $QtDocs" }

Add-Type -AssemblyName System.Web
function ConvertTo-PlainText([string]$html) {
    # Web links keep their address; links within the Qt documentation do not.
    $text = $html -replace '(?s)<a [^>]*href="(https?://[^"]+)"[^>]*>(.*?)</a>', '$2 ($1)'
    $text = $text -replace '(?s)<a [^>]*>(.*?)</a>', '$1'
    $text = $text -replace '(?i)<br\s*/?>|</p>|</pre>|</li>|</h\d>', "`n"
    $text = $text -replace '(?s)<[^>]+>', ''
    return [System.Web.HttpUtility]::HtmlDecode($text).Trim()
}

$out = [System.Text.StringBuilder]::new()
[void]$out.AppendLine("Third-party code in the Qt $QtVersion libraries shipped with SeleneWatch")
[void]$out.AppendLine("=" * 72)
[void]$out.AppendLine("")
[void]$out.AppendLine("SeleneWatch ships Qt Core, Qt Gui, Qt Widgets and Qt Network with the Windows platform,")
[void]$out.AppendLine("style, image format and Schannel TLS plugins under the GNU LGPL version 3")
[void]$out.AppendLine("(licenses/Qt-LICENSE.txt). Qt includes the")
[void]$out.AppendLine("following third-party code, under the licenses given with each. Generated by")
[void]$out.AppendLine("packaging/make_qt_notices.ps1 from the attribution pages of the Qt $QtVersion documentation.")
foreach ($page in $pages | Sort-Object Name) {
    $html = Get-Content $page.FullName -Raw -Encoding UTF8
    $title = if ($html -match '(?s)<h1 class="title"[^>]*>(.*?)</h1>') { ConvertTo-PlainText $Matches[1] } else { $page.BaseName }
    if ($html -notmatch '(?s)<div class="descr" id="details">(.*?)</div>\s*<!-- @@@') { throw "Unexpected page layout: $($page.Name)" }
    [void]$out.AppendLine("")
    [void]$out.AppendLine("-" * 72)
    [void]$out.AppendLine($title)
    [void]$out.AppendLine("-" * 72)
    [void]$out.AppendLine((ConvertTo-PlainText $Matches[1]))
}
$target = Join-Path $PSScriptRoot 'licenses\Qt-third-party-notices.txt'
New-Item -ItemType Directory -Force (Split-Path $target) | Out-Null
[System.IO.File]::WriteAllText($target, ($out.ToString() -replace "`r?`n", "`r`n"), [System.Text.UTF8Encoding]::new($false))
"Wrote $target from $($pages.Count) pages."
